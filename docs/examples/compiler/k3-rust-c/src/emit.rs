// C emission: pretty-prints the IR as readable C with #line directives back to the .p3 source.
use crate::lower::*;
use std::fmt::Write;

fn cstr(s: &str, fmt: bool) -> String {
    let mut o = String::from("\"");
    for ch in s.chars() {
        match ch {
            '\u{1}' if fmt => o.push('%'),
            '%' if fmt => o.push_str("%%"),
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            '\t' => o.push_str("\\t"),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

fn expr(e: &CExpr) -> String {
    match e {
        CExpr::Int(n) => format!("{}", n),
        CExpr::Str(s) => cstr(s, false),
        CExpr::Var(v) => v.clone(),
        CExpr::Field(b, f, ptr) => format!("{}{}{}", expr(b), if *ptr { "->" } else { "." }, f),
        CExpr::Call(f, a) if f == "(long long)" => format!("(long long)({})", expr(&a[0])),
        CExpr::Call(f, a) => format!("{}({})", f, a.iter().map(expr).collect::<Vec<_>>().join(", ")),
        CExpr::Bin(op, l, r) => format!("({} {} {})", expr(l), op, expr(r)),
        CExpr::Ctor(t, fs) => format!("({}){{{}}}", t, fs.iter().map(|(f, v)| format!(".{} = {}", f, expr(v))).collect::<Vec<_>>().join(", ")),
        CExpr::FnRef(n) => n.clone(),
        CExpr::Fmt(f, a) => format!("p3_fmt({}, {})", cstr(f, true), a.iter().map(expr).collect::<Vec<_>>().join(", ")),
    }
}

fn stmts(o: &mut String, v: &[CStmt], ind: usize, src: &str) {
    for s in v {
        if s.line > 0 { writeln!(o, "#line {} \"{}\"", s.line, src).unwrap(); }
        let pad = "    ".repeat(ind);
        match &s.kind {
            CKind::Decl(t, n, i) => match i {
                Some(i) => writeln!(o, "{}{} {} = {};", pad, t, n, expr(i)),
                None => writeln!(o, "{}{} {};", pad, t, n),
            },
            CKind::Assign(l, op, r) => writeln!(o, "{}{} {} {};", pad, expr(l), op, expr(r)),
            CKind::If(c, t, e) => {
                writeln!(o, "{}if {} {{", pad, expr(c)).unwrap();
                stmts(o, t, ind + 1, src);
                if let Some(e) = e {
                    writeln!(o, "{}}} else {{", pad).unwrap();
                    stmts(o, e, ind + 1, src);
                }
                writeln!(o, "{}}}", pad)
            }
            CKind::While(c, b) => {
                writeln!(o, "{}while {} {{", pad, expr(c)).unwrap();
                stmts(o, b, ind + 1, src);
                writeln!(o, "{}}}", pad)
            }
            CKind::Return(None) => writeln!(o, "{}return;", pad),
            CKind::Return(Some(e)) => writeln!(o, "{}return {};", pad, expr(e)),
            CKind::Expr(e, discard) => writeln!(o, "{}{}{};", pad, if *discard { "(void)" } else { "" }, expr(e)),
            CKind::Push(c, t, obj) => {
                writeln!(o, "{}p3_cleanup {};", pad, c).unwrap();
                writeln!(o, "{}p3_push(&{}, {}__drop_thunk, &{});", pad, c, t, obj)
            }
            CKind::PopRun(c) => writeln!(o, "{}p3_pop_run(&{});", pad, c),
        }
        .unwrap();
    }
}

pub fn emit(p: &CProgram, src: &str) -> String {
    let mut o = String::new();
    o.push_str("/* generated by k3c: do not edit. #line directives map back to the .p3 source. */\n#include \"p3rt.h\"\n\n");
    for t in &p.types {
        writeln!(o, "typedef struct {} {{", t.name).unwrap();
        for (f, ty) in &t.fields { writeln!(o, "    {} {};", ty, f).unwrap(); }
        writeln!(o, "}} {};", t.name).unwrap();
    }
    o.push('\n');
    for f in &p.fns {
        writeln!(o, "{}{} {}({});", if f.public { "" } else { "static " }, f.ret, f.name, sig(f)).unwrap();
    }
    for t in p.types.iter().filter(|t| t.has_drop) {
        writeln!(o, "static void {0}__drop_thunk(void *o) {{ {0}__drop(o); }}", t.name).unwrap();
    }
    o.push('\n');
    for f in &p.fns {
        if f.line > 0 { writeln!(o, "#line {} \"{}\"", f.line, src).unwrap(); }
        writeln!(o, "{}{} {}({}) {{", if f.public { "" } else { "static " }, f.ret, f.name, sig(f)).unwrap();
        stmts(&mut o, &f.body, 1, src);
        o.push_str("}\n\n");
    }
    o.push_str("int main(void) {\n    p3_main();\n    return 0;\n}\n");
    o
}

fn sig(f: &CFn) -> String {
    if f.params.is_empty() { return "void".into(); }
    f.params.iter().map(|(t, n)| format!("{} {}", t.trim_end(), n).replace("* ", "*")).collect::<Vec<_>>().join(", ")
}
