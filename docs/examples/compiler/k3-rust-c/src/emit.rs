// C emission: pretty-prints the IR as readable C with #line directives back to the .p3 source.
use crate::lower::*;
use std::fmt::Write;

fn cstr(s: &str, fmt: bool) -> String {
    let mut o = String::from("\"");
    for ch in s.chars() {
        match ch {
            '\u{1}' if fmt => o.push('%'),
            '%' if fmt => o.push_str("%%"),
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            '\t' => o.push_str("\\t"),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

fn expr(e: &CExpr) -> String {
    match e {
        CExpr::Int(n) => format!("{}", n),
        CExpr::Str(s) => cstr(s, false),
        CExpr::Var(v) => v.clone(),
        CExpr::Field(b, f, ptr) => format!("{}{}{}", expr(b), if *ptr { "->" } else { "." }, f),
        CExpr::Call(f, a) if f == "(long long)" => format!("(long long)({})", expr(&a[0])),
        CExpr::Call(f, a) => format!("{}({})", f, a.iter().map(expr).collect::<Vec<_>>().join(", ")),
        CExpr::Bin(op, l, r) => format!("({} {} {})", expr(l), op, expr(r)),
        CExpr::Ctor(t, fs) => format!("({}){{{}}}", t, fs.iter().map(|(f, v)| format!(".{} = {}", f, expr(v))).collect::<Vec<_>>().join(", ")),
        CExpr::FnRef(n) => n.clone(),
        CExpr::EnumCtor(t, v, fs) => format!("({}){{.tag = {}_{}, .u.{} = {{{}}}}}", t, t, v, v, fs.iter().map(|(f, x)| format!(".{} = {}", f, expr(x))).collect::<Vec<_>>().join(", ")),
        CExpr::Raw(r) => r.clone(),
        CExpr::Fmt(f, a) => format!("p3_fmt({}, {})", cstr(f, true), a.iter().map(expr).collect::<Vec<_>>().join(", ")),
    }
}

fn stmts(o: &mut String, v: &[CStmt], ind: usize, src: &str, no_cleanup: bool) {
    for s in v {
        if s.line > 0 { writeln!(o, "#line {} \"{}\"", s.line, src).unwrap(); }
        let pad = "    ".repeat(ind);
        match &s.kind {
            CKind::Decl(t, n, i) => match i {
                Some(i) => writeln!(o, "{}{} {} = {};", pad, t, n, expr(i)),
                None => writeln!(o, "{}{} {};", pad, t, n),
            },
            CKind::Assign(l, op, r) => writeln!(o, "{}{} {} {};", pad, expr(l), op, expr(r)),
            CKind::If(c, t, e) => {
                writeln!(o, "{}if {} {{", pad, expr(c)).unwrap();
                stmts(o, t, ind + 1, src, no_cleanup);
                if let Some(e) = e {
                    writeln!(o, "{}}} else {{", pad).unwrap();
                    stmts(o, e, ind + 1, src, no_cleanup);
                }
                writeln!(o, "{}}}", pad)
            }
            CKind::While(c, b) => {
                writeln!(o, "{}while {} {{", pad, expr(c)).unwrap();
                stmts(o, b, ind + 1, src, no_cleanup);
                writeln!(o, "{}}}", pad)
            }
            CKind::Return(None) => writeln!(o, "{}return;", pad),
            CKind::Return(Some(e)) => writeln!(o, "{}return {};", pad, expr(e)),
            CKind::Expr(e, discard) => writeln!(o, "{}{}{};", pad, if *discard { "(void)" } else { "" }, expr(e)),
            CKind::Push(c, t, obj) => {
                if no_cleanup { continue; } // benchmark build: drops are plain calls, nothing registered for traps
                writeln!(o, "{}p3_cleanup {};", pad, c).unwrap();
                writeln!(o, "{}p3_push(&{}, {}__drop_thunk, &{});", pad, c, t, obj)
            }
            CKind::PopRun(c, t, obj) if no_cleanup && !t.is_empty() => writeln!(o, "{}{}__drop(&{});", pad, t, obj),
            CKind::PopRun(c, _, _) => writeln!(o, "{}p3_pop_run(&{});", pad, c),
            CKind::Block(b) => {
                writeln!(o, "{}{{", pad).unwrap();
                stmts(o, b, ind + 1, src, no_cleanup);
                writeln!(o, "{}}}", pad)
            }
            CKind::CrewBegin(n, line, func) => {
                writeln!(o, "{}p3_crew {};", pad, n).unwrap();
                writeln!(o, "{}p3_crew_begin(&{}, {}, {}, {});", pad, n, cstr(src, false), line, cstr(func, false))
            }
            CKind::Switch(sv, en, arms) => {
                writeln!(o, "{}switch ({}.tag) {{", pad, sv).unwrap();
                for (v, body) in arms {
                    writeln!(o, "{}case {}_{}: {{", pad, en, v).unwrap();
                    stmts(o, body, ind + 1, src, no_cleanup);
                    writeln!(o, "{}    break;\n{}}}", pad, pad).unwrap();
                }
                writeln!(o, "{}}}", pad)
            }
        }
        .unwrap();
    }
}

pub fn emit(p: &CProgram, src: &str, no_cleanup: bool) -> String {
    let mut o = String::new();
    o.push_str("/* generated by k3c: do not edit. #line directives map back to the .p3 source. */\n#include \"p3rt.h\"\n\n");
    // types and enums in source order
    let mut decls: Vec<(u32, String)> = vec![];
    for t in &p.types {
        let mut d = String::new();
        writeln!(d, "typedef struct {} {{", t.name).unwrap();
        for (f, ty) in &t.fields { writeln!(d, "    {} {};", ty, f).unwrap(); }
        writeln!(d, "}} {};", t.name).unwrap();
        decls.push((t.line, d));
    }
    for e in &p.enums {
        let mut d = String::new();
        let tags: Vec<String> = e.variants.iter().map(|(v, _)| format!("{}_{}", e.name, v)).collect();
        writeln!(d, "enum {}_Tag {{ {} }};", e.name, tags.join(", ")).unwrap();
        writeln!(d, "typedef struct {} {{\n    enum {}_Tag tag;", e.name, e.name).unwrap();
        if e.variants.iter().any(|(_, f)| !f.is_empty()) {
            d.push_str("    union {\n");
            for (v, fs) in e.variants.iter().filter(|(_, f)| !f.is_empty()) {
                let body: Vec<String> = fs.iter().map(|(f, t)| format!("{} {};", t, f)).collect();
                writeln!(d, "        struct {{ {} }} {};", body.join(" "), v).unwrap();
            }
            d.push_str("    } u;\n");
        }
        writeln!(d, "}} {};", e.name).unwrap();
        decls.push((e.line, d));
    }
    decls.sort_by_key(|d| d.0);
    for (_, d) in decls { o.push_str(&d); }
    o.push('\n');
    for f in &p.fns {
        writeln!(o, "{}{} {}({});", if f.public { "" } else { "static " }, f.ret, f.name, sig(f)).unwrap();
    }
    for t in p.types.iter().filter(|t| t.has_drop && !no_cleanup) {
        writeln!(o, "static void {0}__drop_thunk(void *o) {{ {0}__drop(o); }}", t.name).unwrap();
    }
    o.push('\n');
    for f in &p.fns {
        if f.line > 0 { writeln!(o, "#line {} \"{}\"", f.line, src).unwrap(); }
        writeln!(o, "{}{} {}({}) {{", if f.public { "" } else { "static " }, f.ret, f.name, sig(f)).unwrap();
        stmts(&mut o, &f.body, 1, src, no_cleanup);
        o.push_str("}\n\n");
    }
    o.push_str("int main(void) {\n    p3_main();\n    return 0;\n}\n");
    o
}

fn sig(f: &CFn) -> String {
    if f.params.is_empty() { return "void".into(); }
    f.params.iter().map(|(t, n)| format!("{} {}", t.trim_end(), n).replace("* ", "*")).collect::<Vec<_>>().join(", ")
}

/// Line table for coverage: for every generated C line that directly follows a `#line N "file"`
/// directive, "<C line> <source line>". Continuation lines (closing braces, `} else {`) are left out.
pub fn line_map(c: &str, src: &str) -> String {
    let mut m = format!("# k3 line map v1: <C line> <line in {}>\n", src);
    let mut pending: Option<u32> = None;
    for (i, l) in c.lines().enumerate() {
        if let Some(rest) = l.strip_prefix("#line ") {
            pending = rest.split_whitespace().next().and_then(|n| n.parse().ok());
            continue;
        }
        if let Some(n) = pending.take() { writeln!(m, "{} {}", i + 1, n).unwrap(); }
    }
    m
}
